// Bundles the Electron main and preload processes to CommonJS (Electron loads CJS for main).
import { build } from 'esbuild';
import { copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  entryPoints: { main: join(root, 'src/main.ts'), preload: join(root, 'src/preload.ts') },
  outdir: join(root, 'dist'),
  outExtension: { '.js': '.cjs' },
  bundle: true,
  platform: 'node',
  target: 'node24', // Electron 44 ships Node 24
  format: 'cjs',
  external: ['electron'],
  sourcemap: true,
  logLevel: 'info',
});

// Icon used for the window and taskbar in development (generated by scripts/make-icons.mjs).
mkdirSync(join(root, 'build/icons'), { recursive: true });
try {
  copyFileSync(join(root, '../../docs/branding/mediescare-icon.svg'), join(root, 'build/icons/icon.svg'));
} catch {
  /* branding folder missing: the window falls back to the default icon */
}
