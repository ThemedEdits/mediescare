// Bundles the Electron main and preload processes to CommonJS (Electron loads CJS for main).
import { build } from 'esbuild';
import { copyFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

await build({
  entryPoints: {
    main: join(root, 'src/main.ts'),
    preload: join(root, 'src/preload.ts'),
    'restore-cli': join(root, 'src/restore-cli.ts'),
  },
  outdir: join(root, 'dist'),
  outExtension: { '.js': '.cjs' },
  bundle: true,
  platform: 'node',
  target: 'node24', // Electron 44 ships Node 24
  format: 'cjs',
  // Native modules stay external: the restore tool runs next to the web server's node_modules.
  external: ['electron', 'better-sqlite3', '@node-rs/argon2'],
  sourcemap: true,
  logLevel: 'info',
});

// Icon used for the window and taskbar in development (generated by scripts/make-icons.mjs).
mkdirSync(join(root, 'build/icons'), { recursive: true });
try {
  copyFileSync(
    join(root, '../../docs/branding/mediescare-icon.svg'),
    join(root, 'build/icons/icon.svg'),
  );
} catch {
  /* branding folder missing: the window falls back to the default icon */
}
